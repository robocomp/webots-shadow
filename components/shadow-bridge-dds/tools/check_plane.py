#!/usr/bin/env python3
"""check_plane.py — is the media plane up, and how old is each stream on arrival?

1. Queries the five MediaPlaneDDS descriptor endpoints robot_concept reads (zed, ricoh, helios, bpearl,
   imu) and prints what each advertises (topics, ready, LiDAR rings/elevations).
2. Runs common/media_transport's lag_probe on every stream: total age, split into upstream (capture ->
   DDS write) and transport (write -> take).

Works against either deployment (sub_shadow.toml drivers or sub_shadow_dds.toml bridge), so the two
can be compared with the same instrument.   Usage:  tools/check_plane.py [seconds_per_stream=5]
"""
import json
import os
import subprocess
import sys
import tempfile

import Ice

ENDPOINTS = [("zed", 12002), ("ricoh", 10099), ("helios", 11890), ("bpearl", 11889), ("imu", 11891)]
STREAMS = [("lidar", "rc/lidar3d/points"), ("lidar", "rc/lidar3d/bpearl"), ("image", "rc/zed/rgb"),
           ("image", "rc/zed/depth"), ("image360", "rc/ricoh/rgb"), ("imu", "rc/imu/data")]
HERE = os.path.dirname(os.path.abspath(__file__))
LAG_PROBE = os.path.normpath(os.path.join(
    HERE, "../../../../active_inference/common/media_transport/build/lag_probe"))
IDSL_ICE = "module RoboCompMediaPlaneDDS { interface MediaPlaneDDS { string getMediaDescriptor(); }; };\n"


def descriptors():
    with tempfile.NamedTemporaryFile("w", suffix=".ice", delete=False) as f:
        f.write(IDSL_ICE)
        path = f.name
    Ice.loadSlice(path)
    import RoboCompMediaPlaneDDS  # noqa: E402  (generated by loadSlice)
    with Ice.initialize(["--Ice.Default.Timeout=1000"]) as ic:
        for node, port in ENDPOINTS:
            try:
                prx = RoboCompMediaPlaneDDS.MediaPlaneDDSPrx.checkedCast(
                    ic.stringToProxy(f"mediaplanedds:tcp -h localhost -p {port}"))
                text = prx.getMediaDescriptor()
            except Exception as e:  # unreachable endpoint = nobody serving that node
                print(f"{node:7s} :{port}  UNREACHABLE ({type(e).__name__})")
                continue
            if not text:
                print(f"{node:7s} :{port}  serving, but EMPTY descriptor (not publishing yet)")
                continue
            d = json.loads(text)   # flat keys: "<stream>_topic", "geom_*" (MediaDescriptor::to_json)
            topics = {k[:-6]: v for k, v in d.items() if k.endswith("_topic")}
            line = f"{node:7s} :{port}  ready={d.get('ready')} type={d.get('type_name')} topics={topics}"
            if "geom_rings" in d or "geom_ring_elev_deg" in d:
                elev = d.get("geom_ring_elev_deg", "")
                n = len(elev) if isinstance(elev, list) else len([x for x in str(elev).split(";") if x])
                line += (f"\n{'':15s}model: rings={d.get('geom_rings')} elevations={n} "
                         f"fov=[{d.get('geom_fov_start_deg')}..{d.get('geom_fov_end_deg')}] az={d.get('geom_azimuth_step_deg')}")
            print(line)


def lags(secs):
    if not os.path.exists(LAG_PROBE):
        print(f"\n(lag_probe not built at {LAG_PROBE}; skipping the latency part)")
        return
    print()
    for kind, topic in STREAMS:
        out = subprocess.run([LAG_PROBE, kind, topic, "7", str(secs)], capture_output=True, text=True).stdout
        print("\n".join(l for l in out.splitlines() if not l.startswith("[")))


if __name__ == "__main__":
    descriptors()
    lags(float(sys.argv[1]) if len(sys.argv) > 1 else 5)
